<?php

declare(strict_types=1);

namespace Angeo\AeoAudit\Test\Unit\Model\Checker;

use Angeo\AeoAudit\Model\Checker\LlmsTxtChecker;
use Angeo\AeoAudit\Service\StoreUrlSampler;
use Magento\Store\Model\Store;
use Magento\Store\Model\StoreManagerInterface;
use PHPUnit\Framework\TestCase;

class LlmsTxtCheckerTest extends TestCase
{
    use CheckerTestHelper;

    private LlmsTxtChecker $checker;

    protected function setUp(): void
    {
        $this->bootCheckerMocks('https://example.com');
        $storeManager = $this->createMock(StoreManagerInterface::class);
        $storeManager->method('getStores')->willReturn([$this->store]);
        $this->checker = new LlmsTxtChecker($this->httpCache, $this->urlSampler, $storeManager);
    }

    /**
     * Checker for an installation with two store views: example.com (id 1,
     * the audited one) and de.example.com (id 2).
     */
    private function checkerWithSiblingStore(): LlmsTxtChecker
    {
        $sibling = $this->createMock(Store::class);
        $sibling->method('getId')->willReturn(2);

        $sampler = $this->createMock(StoreUrlSampler::class);
        $sampler->method('getBaseUrl')->willReturnCallback(
            static fn ($store): string => (int) $store->getId() === 2 ? 'https://de.example.com' : 'https://example.com'
        );

        $storeManager = $this->createMock(StoreManagerInterface::class);
        $storeManager->method('getStores')->willReturn([$this->store, $sibling]);

        return new LlmsTxtChecker($this->httpCache, $sampler, $storeManager);
    }

    public function testFailWhenMissing(): void
    {
        $this->stubUrl('https://example.com/llms.txt', 404, '');
        $result = $this->checker->check($this->store);
        $this->assertTrue($result->isFailed());
    }

    public function testPassWithMinimalValidFile(): void
    {
        $body = <<<TXT
# Example Store

A brief description of Example Store, selling widgets since 2020.

## Products

- [Widget A](https://example.com/widget-a)
- [Widget B](https://example.com/widget-b)
TXT;
        $this->stubUrl('https://example.com/llms.txt', 200, $body);
        $result = $this->checker->check($this->store);
        // Passes with possible minor warning about metadata, but should be PASS or WARN
        $this->assertNotTrue($result->isFailed(), 'Got FAIL: ' . $result->getMessage());
    }

    public function testFailWhenMissingH1(): void
    {
        $body = <<<TXT
Just description without an H1 title

## Section
- [Link](https://example.com/page)
TXT;
        $this->stubUrl('https://example.com/llms.txt', 200, $body);
        $result = $this->checker->check($this->store);
        $this->assertTrue($result->isFailed());
        $this->assertStringContainsString('H1', $result->getRecommendation());
    }

    public function testLinksToAnotherStoreViewAreAWarning(): void
    {
        $body = <<<TXT
# Example Store

A description here. Currency: USD. Language: en.

## Products
- [Our Page](https://example.com/page)
- [German Page](https://de.example.com/seite)
TXT;
        $this->stubUrl('https://example.com/llms.txt', 200, $body);
        $this->stubUrl('https://example.com/page', 200, 'ok');
        $this->stubUrl('https://de.example.com/seite', 200, 'ok');

        $result = $this->checkerWithSiblingStore()->check($this->store);

        $this->assertTrue($result->isWarning(), $result->getMessage());
        $this->assertStringContainsString('another store view', $result->getRecommendation());
        $this->assertSame(1, $result->getDetails()['other_store_links']);
        $this->assertSame(0, $result->getDetails()['external_links']);
    }

    /**
     * 4.6.0: links to outside sites are normal markdown. demo.angeo.dev got a
     * WARN for the generator credit that angeo/module-llms-txt itself adds.
     */
    public function testLinksToOutsideSitesAreNotAWarning(): void
    {
        $body = <<<TXT
# Example Store

A description here. Currency: USD. Language: en.

## Products
- [Our Page](https://example.com/page)
- [Brand on Wikipedia](https://en.wikipedia.org/wiki/Example)

---

Generated by [Angeo LlmsTxt](https://angeo.dev/?utm_source=llms-txt&utm_medium=signature) — open-source AEO module.
TXT;
        $this->stubUrl('https://example.com/llms.txt', 200, $body);
        $this->stubUrl('https://example.com/page', 200, 'ok');
        $this->stubUrl('https://en.wikipedia.org/wiki/Example', 200, 'ok');
        $this->stubUrl('https://angeo.dev/?utm_source=llms-txt&utm_medium=signature', 200, 'ok');

        $result = $this->checkerWithSiblingStore()->check($this->store);

        $this->assertTrue($result->isPassed(), $result->getMessage() . ' | ' . $result->getRecommendation());
        $this->assertSame(0, $result->getDetails()['other_store_links']);
        $this->assertSame(2, $result->getDetails()['external_links']);
    }
}
